export function initialLanguage(search, storage, browserLanguage) {
  const url = new URLSearchParams(search).get('lang');
  if (Object.hasOwn(dictionaries, url)) return url;
  try {
    const stored = storage?.getItem('sc-language');
    if (Object.hasOwn(dictionaries, stored)) return stored;
  } catch {
    // Storage may be blocked in private browsing or file previews.
  }
  const browser = (browserLanguage || '').split('-')[0].toLowerCase();
  return Object.hasOwn(dictionaries, browser) ? browser : 'ja';
}

export function translate(language, key) {
  if (dictionaries[language]?.[key]) return dictionaries[language][key];
  console.warn(`Missing translation: ${language}:${key}`);
  return dictionaries.ja[key] || key;
}

export function localized(value, language) {
  if (typeof value?.[language] === 'string') return value[language];
  console.warn(`Missing property translation: ${language}`);
  return value?.ja || '';
}
